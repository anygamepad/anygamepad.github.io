import { readFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { defineConfig, type Plugin } from "vite";
import { jq79 } from "jq79/vite";

// The database the settings send the activity log and test reports to
// (roadmap P2, P6), when the person turns sending on: none until it runs. A
// build with ANYGAMEPAD_SYNC_URL names it to the page in a <meta> tag
// (src/sync.ts reads it) and lets the page connect to its origin.
const syncUrl = (): URL | null => {
  const value = process.env.ANYGAMEPAD_SYNC_URL;
  if (!value) return null;
  const url = new URL(value.endsWith("/") ? value : `${value}/`);
  const local = url.hostname === "127.0.0.1" || url.hostname === "localhost";
  if (url.protocol !== "https:" && !(local && url.protocol === "http:")) {
    throw new Error(`ANYGAMEPAD_SYNC_URL must be an https URL, not ${value}`);
  }
  return url;
};
const SYNC_URL = syncUrl();

// GitHub Pages cannot send headers, so the policy travels as a <meta> tag
// (ADR 0005). WebAssembly needs 'wasm-unsafe-eval'; jq79's safeEval mode
// removes the need for 'unsafe-eval' and inline styles. Production builds
// only: the dev server injects inline scripts and styles of its own.
const CONTENT_SECURITY_POLICY = [
  "default-src 'self'",
  "script-src 'self' 'wasm-unsafe-eval'",
  "style-src 'self'",
  "img-src 'self'",
  SYNC_URL ? `connect-src 'self' ${SYNC_URL.origin}` : "connect-src 'self'",
  "object-src 'none'",
  "base-uri 'self'",
  "form-action 'self'",
].join("; ");

const contentSecurityPolicy = (): Plugin => ({
  name: "anygamepad:content-security-policy",
  apply: "build",
  transformIndexHtml: () => [
    {
      tag: "meta",
      attrs: { "http-equiv": "Content-Security-Policy", content: CONTENT_SECURITY_POLICY },
      injectTo: "head-prepend",
    },
  ],
});

const syncEndpoint = (): Plugin => ({
  name: "anygamepad:sync-endpoint",
  transformIndexHtml: () =>
    SYNC_URL ? [{ tag: "meta", attrs: { name: "anygamepad-sync", content: SYNC_URL.href }, injectTo: "head" }] : [],
});

// The JSON Schemas of device profiles (roadmap D1), device reports (P1),
// catalog models and lab inventories (H2), test reports (H1) and test
// plans (H3), published at the URLs of their `$id` for editors and tools.
// Generated by the anygamepad-db and anygamepad-report tests.
const SCHEMAS = {
  "schema/profile.json": "../../data/profiles/schema.json",
  "schema/report.json": "../../data/reports/schema.json",
  "schema/controller.json": "../../data/controllers/schema.json",
  "schema/inventory.json": "../../data/lab/schema.json",
  "schema/test-report.json": "../../data/test-reports/schema.json",
  "schema/test-plan.json": "../../data/test-plans/schema.json",
};

const schemas = (): Plugin => ({
  name: "anygamepad:schemas",
  apply: "build",
  generateBundle() {
    for (const [fileName, path] of Object.entries(SCHEMAS)) {
      this.emitFile({
        type: "asset",
        fileName,
        source: readFileSync(new URL(path, import.meta.url), "utf8"),
      });
    }
  },
});

// Controller illustrations (src/art/*.svg, imported `?raw`) ship without
// their comments and indentation, which document the markup in the source.
const minifiedArt = (): Plugin => ({
  name: "anygamepad:minified-art",
  apply: "build",
  enforce: "pre",
  load(id) {
    const [path, query] = id.split("?");
    if (query !== "raw" || !path?.endsWith(".svg")) return null;
    const svg = readFileSync(path, "utf8")
      .replace(/<!--[\s\S]*?-->/g, "")
      .replace(/>\s+</g, "><")
      .replace(/\s+/g, " ")
      .trim();
    return `export default ${JSON.stringify(svg)};`;
  },
});

export default defineConfig({
  plugins: [jq79({ safeEval: true }), contentSecurityPolicy(), syncEndpoint(), schemas(), minifiedArt()],
  build: {
    // The tester, the test mode (H4) at /test/, and the privacy policy
    // (roadmap P3) at /privacy/.
    rolldownOptions: {
      input: {
        main: fileURLToPath(new URL("index.html", import.meta.url)),
        test: fileURLToPath(new URL("test/index.html", import.meta.url)),
        privacy: fileURLToPath(new URL("privacy/index.html", import.meta.url)),
      },
    },
    // Top-level await, which safeEval's component modules use.
    target: "es2022",
    // Every asset, jq79's precompiled scripts included, stays a file:
    // `script-src 'self'` refuses data: URLs.
    assetsInlineLimit: 0,
  },
});
