import { readFileSync } from "node:fs";
import { defineConfig, type Plugin } from "vite";
import { jq79 } from "jq79/vite";

// GitHub Pages cannot send headers, so the policy travels as a <meta> tag
// (ADR 0005). WebAssembly needs 'wasm-unsafe-eval'; jq79's safeEval mode
// removes the need for 'unsafe-eval' and inline styles. Production builds
// only: the dev server injects inline scripts and styles of its own.
const CONTENT_SECURITY_POLICY = [
  "default-src 'self'",
  "script-src 'self' 'wasm-unsafe-eval'",
  "style-src 'self'",
  "img-src 'self'",
  "connect-src 'self'",
  "object-src 'none'",
  "base-uri 'self'",
  "form-action 'self'",
].join("; ");

const contentSecurityPolicy = (): Plugin => ({
  name: "anygamepad:content-security-policy",
  apply: "build",
  transformIndexHtml: () => [
    {
      tag: "meta",
      attrs: { "http-equiv": "Content-Security-Policy", content: CONTENT_SECURITY_POLICY },
      injectTo: "head-prepend",
    },
  ],
});

// The JSON Schema of device profiles (roadmap D1), published at the URL of
// its `$id` for editors and tools. Generated by the anygamepad-db tests.
const profileSchema = (): Plugin => ({
  name: "anygamepad:profile-schema",
  apply: "build",
  generateBundle() {
    this.emitFile({
      type: "asset",
      fileName: "schema/profile.json",
      source: readFileSync(new URL("../../data/profiles/schema.json", import.meta.url), "utf8"),
    });
  },
});

// Controller illustrations (src/art/*.svg, imported `?raw`) ship without
// their comments and indentation, which document the markup in the source.
const minifiedArt = (): Plugin => ({
  name: "anygamepad:minified-art",
  apply: "build",
  enforce: "pre",
  load(id) {
    const [path, query] = id.split("?");
    if (query !== "raw" || !path?.endsWith(".svg")) return null;
    const svg = readFileSync(path, "utf8")
      .replace(/<!--[\s\S]*?-->/g, "")
      .replace(/>\s+</g, "><")
      .replace(/\s+/g, " ")
      .trim();
    return `export default ${JSON.stringify(svg)};`;
  },
});

export default defineConfig({
  plugins: [jq79({ safeEval: true }), contentSecurityPolicy(), profileSchema(), minifiedArt()],
  build: {
    // Top-level await, which safeEval's component modules use.
    target: "es2022",
    // Every asset, jq79's precompiled scripts included, stays a file:
    // `script-src 'self'` refuses data: URLs.
    assetsInlineLimit: 0,
  },
});
